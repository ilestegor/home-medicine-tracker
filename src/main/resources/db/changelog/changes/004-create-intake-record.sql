--comment: Факт приёма. Единственная сущность, меняющая чужое состояние.
-- Списывает stock_item.quantity в той же транзакции.
-- FK на stock_item — RESTRICT: история не теряется вместе с упаковкой.
-- FK на regimen — SET NULL: удалённый курс оставляет приёмы как разовые.
create table intake_record
(
    id            bigint generated by default as identity,
    stock_item_id bigint         not null,
    regimen_id    bigint,
    amount        numeric(10, 2) not null,
    taken_at      timestamptz    not null,
    note          text,
    created_at    timestamptz    not null default now(),
    updated_at    timestamptz    not null default now(),

    constraint pk_intake_record primary key (id),
    constraint fk_intake_record_stock_item foreign key (stock_item_id)
        references stock_item (id) on delete restrict,
    constraint fk_intake_record_regimen foreign key (regimen_id)
        references regimen (id) on delete set null,

    constraint ck_intake_record_amount_positive check (amount > 0)
);

comment on column intake_record.regimen_id is 'NULL = разовый приём вне курса';
