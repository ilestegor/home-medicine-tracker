--comment: Справочник препаратов — корень графа. Что это за лекарство вообще, а не что лежит дома.
create table medicine
(
    id           bigint generated by default as identity,
    name         varchar(200) not null,
    inn          varchar(200),
    form         varchar(30),
    dosage       varchar(50),
    manufacturer varchar(200),
    notes        text,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now(),

    constraint pk_medicine primary key (id),

    -- NULLS NOT DISTINCT нужен потому, что dosage необязателен: обычный UNIQUE
    -- считает NULL-ы различными и пропустил бы два «Нурофена» без дозировки.
    -- Требует PostgreSQL 15+.
    constraint uq_medicine_name_dosage
        unique nulls not distinct (name, dosage)
);

