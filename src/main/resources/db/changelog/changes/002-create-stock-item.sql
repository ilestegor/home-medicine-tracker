--comment: Физическая упаковка на полке. ON DELETE RESTRICT — удаление препарата не уносит упаковки молча.
create table stock_item
(
    id               bigint generated by default as identity,
    medicine_id      bigint        not null,
    quantity         numeric(10, 2) not null,
    initial_quantity numeric(10, 2) not null,
    unit             varchar(20)   not null,
    expires_at       date          not null,
    opened_at        date,
    status           varchar(20)   not null default 'ACTIVE',
    created_at       timestamptz   not null default now(),
    updated_at       timestamptz   not null default now(),

    constraint pk_stock_item primary key (id),
    constraint fk_stock_item_medicine foreign key (medicine_id)
        references medicine (id) on delete restrict,

    -- Списание идёт из сервиса в транзакции, но CHECK — последний рубеж:
    -- даже прямой UPDATE в psql не уведёт остаток в минус.
    constraint ck_stock_item_quantity_non_negative     check (quantity >= 0),
    constraint ck_stock_item_initial_quantity_positive check (initial_quantity > 0),
    constraint ck_stock_item_quantity_not_over_initial check (quantity <= initial_quantity),
    constraint ck_stock_item_status                    check (status in ('ACTIVE', 'FINISHED', 'DISCARDED'))
);

