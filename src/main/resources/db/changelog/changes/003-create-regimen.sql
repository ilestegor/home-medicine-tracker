--comment: Схема приёма: что, сколько и как часто принимать.
-- Ссылается на medicine, а не на stock_item: курс переживает упаковку — пачка
-- кончилась на шестой день из десяти, открыл новую, схема та же.
create table regimen
(
    id            bigint generated by default as identity,
    medicine_id   bigint         not null,
    dose_amount   numeric(10, 2) not null,
    dose_unit     varchar(20)    not null,
    times_per_day smallint       not null,
    starts_on     date           not null,
    ends_on       date,
    instructions  text,
    active        boolean        not null default true,
    created_at    timestamptz    not null default now(),
    updated_at    timestamptz    not null default now(),

    constraint pk_regimen primary key (id),
    constraint fk_regimen_medicine foreign key (medicine_id)
        references medicine (id) on delete restrict,

    constraint ck_regimen_dose_amount_positive check (dose_amount > 0),
    constraint ck_regimen_times_per_day        check (times_per_day between 1 and 24),
    constraint ck_regimen_period               check (ends_on is null or ends_on >= starts_on)
);

comment on column regimen.ends_on is 'NULL = бессрочный приём';
